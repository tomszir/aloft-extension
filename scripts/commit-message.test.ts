import { describe, expect, it } from 'vitest'
import { checkAttribution, checkCommitMessage, checkHeader } from './commit-message'

describe('checkHeader', () => {
  it.each([
    'feat: pinned tabs row',
    'fix(palette): keep focus after closing the menu',
    'feat!: drop chrome 120',
    'chore(main): release 0.2.0',
    'fixup! feat: pinned tabs row',
    'Revert "feat: pinned tabs row"',
  ])('accepts %s', (header) => {
    expect(checkHeader(header)).toEqual([])
  })

  it.each([
    ['Add pinned tabs', 'conventional'],
    ['feature: pinned tabs', 'conventional'],
    ['feat:missing space', 'conventional'],
    ['feat(Palette): upper-case scope', 'conventional'],
    ['feat: Pinned tabs row', 'lowercase'],
    ['feat: pinned tabs row.', 'period'],
    [`feat: ${'x'.repeat(70)}`, '72'],
  ])('rejects %s', (header, problem) => {
    expect(checkHeader(header).join(' ')).toContain(problem)
  })
})

describe('checkAttribution', () => {
  it.each([
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'co-authored-by: GitHub Copilot <copilot@github.com>',
    'Generated with Claude Code',
    'generated by ChatGPT',
    '🤖 made by a robot',
  ])('rejects %s', (text) => {
    expect(checkAttribution(text)).not.toEqual([])
  })

  it.each([
    'Co-Authored-By: A Person <person@example.com>',
    'This PR was generated with Release Please.',
    'Regenerated with the icon vendor script.',
  ])('allows %s', (text) => {
    expect(checkAttribution(text)).toEqual([])
  })
})

describe('checkCommitMessage', () => {
  it('ignores git comment lines and checks the whole message', () => {
    const message =
      '# Please enter the commit message\nfix: a bug\n\nbody\n\nCo-Authored-By: Claude <x@y>\n'
    expect(checkCommitMessage(message)).toEqual(['remove the AI Co-Authored-By trailer'])
  })

  it('rejects an empty message', () => {
    expect(checkCommitMessage('# only comments\n\n')).toEqual(['the commit message is empty'])
  })
})
